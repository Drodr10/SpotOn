// Expo config plugin: rounded Android autofill highlight.
//
// When Android autofills a field (Google Password Manager, etc.) it draws the
// theme's android:autofilledHighlight over it. The platform default is a
// RECTANGULAR yellow tint, which looks broken over our rounded pill inputs.
// This swaps it for a pill-shaped (999dp corners), subtle blue tint that sits
// well on the chalk-grey cards.
//
// (a) writes res/drawable/autofill_highlight.xml
// (b) sets <item name="android:autofilledHighlight"> on AppTheme
//
// iOS is untouched (it has no equivalent overlay). frontend/android is
// generated, so re-run `npx expo prebuild -p android` after changing this.

const fs = require('fs');
const path = require('path');
const { withAndroidStyles, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const DRAWABLE_NAME = 'autofill_highlight';
// ~12% of SpotOn's blue: visible on the light grey card without shouting.
const TINT = '#1F1E56B8';

const DRAWABLE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAutofillHighlight.js: rounded autofill tint. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="${TINT}" />
    <corners android:radius="999dp" />
</shape>
`;

function withAutofillHighlightDrawable(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${DRAWABLE_NAME}.xml`), DRAWABLE_XML);
      return cfg;
    },
  ]);
}

function withAutofillHighlightTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    cfg.modResults = AndroidConfig.Styles.assignStylesValue(cfg.modResults, {
      add: true,
      parent: AndroidConfig.Styles.getAppThemeGroup(),
      name: 'android:autofilledHighlight',
      value: `@drawable/${DRAWABLE_NAME}`,
    });
    return cfg;
  });
}

module.exports = function withAutofillHighlight(config) {
  return withAutofillHighlightTheme(withAutofillHighlightDrawable(config));
};
